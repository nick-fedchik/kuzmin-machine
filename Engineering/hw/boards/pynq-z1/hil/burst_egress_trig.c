/* ============================================================================
 * Машина Кузьміна (Kuzmin Machine) — Пакетний генератор стимулів PYNQ-Z1 (#226)
 * Файл: Engineering/hw/boards/pynq-z1/hil/burst_egress_trig.c
 *
 * Завантажує 4-концептний ендогенний каскад C0 -> C1 -> C2 -> C3 у Block RAM
 * конвеєра CFG-P (0x40000000) з бітстрімом pipeline_egress.bit та генерує
 * пакет із 200 послідовних запусків каскаду через регістр 0x010 (REG_TRIGGER=1)
 * з очікуванням звільнення конвеєра (0x014 REG_BUSY == 0) між запусками.
 *
 * На піні PMOD JA2 (JA2_COMMIT, канал CH2 / GP3 аналізатора LOGICTRACER_PICO)
 * кожен 4-концептний каскад формує злитий високий імпульс шириною:
 *   T_high = 3 * 80 нс + 100 нс = 340 нс (34 такти @ 100 МГц),
 * розділений низькою паузою ~250..300 нс на цикл опитування MMIO AXI GP0
 * з процесора ARM Cortex-A9 (період повторення ~600 нс, 200 імпульсів = 400 фронтів).
 * ============================================================================ */

#include <fcntl.h>
#include <stdint.h>
#include <stdio.h>
#include <sys/mman.h>
#include <unistd.h>

int main(void) {
    int fd = open("/dev/mem", O_RDWR | O_SYNC);
    if (fd < 0) {
        perror("open /dev/mem");
        return 1;
    }
    volatile uint32_t *pl = (volatile uint32_t *)mmap(
        NULL, 0x2000, PROT_READ | PROT_WRITE, MAP_SHARED, fd, 0x40000000UL
    );
    if (pl == MAP_FAILED) {
        perror("mmap 0x40000000");
        close(fd);
        return 1;
    }

    /* Завантаження дескрипторів 4-концептного каскаду C0 -> C1 -> C2 -> C3 */
    pl[0x004 >> 2] = 0;  pl[0x008 >> 2] = 10u;
    pl[0x004 >> 2] = 1;  pl[0x008 >> 2] = 50u;
    pl[0x004 >> 2] = 2;  pl[0x008 >> 2] = 0x01001304u;
    pl[0x004 >> 2] = 3;  pl[0x008 >> 2] = 0x00000001u;

    pl[0x004 >> 2] = 4;  pl[0x008 >> 2] = 0u;
    pl[0x004 >> 2] = 5;  pl[0x008 >> 2] = 10u;
    pl[0x004 >> 2] = 6;  pl[0x008 >> 2] = 0x01001303u;
    pl[0x004 >> 2] = 7;  pl[0x008 >> 2] = 0x00000002u;

    pl[0x004 >> 2] = 8;  pl[0x008 >> 2] = 0u;
    pl[0x004 >> 2] = 9;  pl[0x008 >> 2] = 0u;
    pl[0x004 >> 2] = 10; pl[0x008 >> 2] = 0x01001303u;
    pl[0x004 >> 2] = 11; pl[0x008 >> 2] = 0x00000003u;

    pl[0x004 >> 2] = 12; pl[0x008 >> 2] = 0u;
    pl[0x004 >> 2] = 13; pl[0x008 >> 2] = 0u;
    pl[0x004 >> 2] = 14; pl[0x008 >> 2] = 0x00000303u;
    pl[0x004 >> 2] = 15; pl[0x008 >> 2] = 0x00000000u;

    /* Пакет із 200 каскадних запусків через AXI GP0 MMIO */
    for (int i = 0; i < 200; ++i) {
        pl[0x00C >> 2] = 10u;
        pl[0x010 >> 2] = 1u;
        while (pl[0x014 >> 2] != 0u) {
            /* Очікування завершення 4x8=32 тактів каскаду в секвенсері */
        }
    }

    munmap((void *)pl, 0x2000);
    close(fd);
    return 0;
}
