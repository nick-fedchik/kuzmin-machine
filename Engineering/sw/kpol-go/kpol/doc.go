// Package kpol implements the KPOL language toolchain: lexer, parser, static
// semantics, reference interpreter, Proof verification and the CME-RAW-1
// profile compilers (KPOL-CME-1 / KPOL-CME-2).
//
// The normative definition is Engineering/specifications/kpol/
// kpol-formal-specification.md. The Python reference implementation in
// Engineering/sw/kpol-ref/kpol_reference.py is the oracle for the differential
// tests in this package (testdata/gen_kpol_golden.py writes
// testdata/kpol_golden.json).
//
// # Front end
//
// Tokenize implements KPOL-LEX-1..6, ParseUnchecked (alias ParseSyntax)
// KPOL-SYN-1..8, Check the static semantics KPOL-STA-1..13, and Parse is the
// reference parse_module: ParseUnchecked followed by Check. ParseTriad links
// separate problem, solution and proof sources.
//
// Lexical and syntactic errors read "line:column: message"; static and runtime
// errors have no position. All of them are *Error values whose Msg is
// byte-identical to the message of the reference KpolError and whose Code is
// empty. Where the reference dies with an unhandled Python exception (the
// literal "²", a binary float mixed with a Decimal, decimal overflow, ...) the
// port returns an *Error with one of the Code* constants instead.
//
// Character classes follow the reference, which uses Python's str.isalpha,
// isdigit, isalnum and isspace (D-K1); the tables are frozen from Python 3.14
// (Unicode 16) in pyunicode_tables.go, generated by testdata/gen_pyunicode.py.
//
// # Dynamic semantics
//
// Value is one of Bool, Int, Decimal, Float and Unknown. Decimal reproduces
// Python's decimal arithmetic under the default context (28 significant
// digits, round-half-even); Float is a binary double that only arises from
// dividing two integers (D-K2). EvalExpr evaluates an expression with strong
// Kleene logic (KPOL-DYN-3). NewInterpreter computes σ₀ (KPOL-DYN-4) and
// Interpreter.Run implements the event loop, the presentation phases A/B/C and
// the transaction TX with its change cascade (KPOL-DYN-5..8). Verify implements
// the Proof semantics (KPOL-PRF-1). FormatValue renders values the way Python
// prints them, so results can be compared with the reference text.
//
// # Deliberate differences from the reference
//
//   - Unhandled Python exceptions become *Error values with a Code (see codes.go).
//   - An EventInput named "change" is always rejected ("invalid internal change
//     event"): internal change events carry a Python tuple that has no Go
//     counterpart and are generated only by the interpreter. The internal
//     "_watch" payload key is not visible to expressions.
//   - Strings are UTF-8; lone surrogates and invalid bytes read as U+FFFD.
//   - Expression nesting is limited to 10000 levels (CodeParseDepth) instead of
//     Python's recursion limit.
//   - Pin<p1,...,pn> keeps its parameters in TypeRef.PinParams (the reference
//     stores them joined by commas in the unit field); Unit is empty for Pin.
//   - A DecLit keeps its source digits normalised to ASCII; AST nodes are
//     plain values (Binary, not *Binary).
