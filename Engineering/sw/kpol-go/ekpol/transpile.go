package ekpol

import (
	"math/big"
	"regexp"
	"strings"
)

var reCNumber = regexp.MustCompile(`^C[0-9]+$`)

func canonicalEventName(c *Concept, r *Rule, total int) string {
	if r.EventName != "" {
		return r.EventName
	}
	if total == 1 && c.Name == "Counter" {
		return "Pulse"
	}
	if reCNumber.MatchString(c.Name) {
		return "E" + c.Name[1:]
	}
	cleaned := strings.ReplaceAll(strings.ReplaceAll(c.Name, "_mV", ""), "_", "")
	return "Ev" + cleaned
}

func canonicalRuleName(c *Concept, total int) string {
	if total == 1 && c.Name == "Counter" {
		return "Step"
	}
	if reCNumber.MatchString(c.Name) {
		return "R" + c.Name[1:]
	}
	return "R_" + c.Name
}

// predicateToKPOLGuard renders a predicate as a KPOL guard expression (section 10.1).
func predicateToKPOLGuard(p *Predicate) string {
	wrap := func(base string) string {
		if p.Inverted {
			return "not (" + base + ")"
		}
		return base
	}
	switch p.Kind {
	case PredNop:
		if p.Inverted {
			return "false"
		}
		return "true"
	case PredRange:
		return wrap(p.Var + " >= " + p.Lo.String() + " and " + p.Var + " <= " + p.Hi.String())
	case PredCmp:
		return wrap(p.Var + " " + p.Op + " " + p.Value.String())
	case PredBitmask:
		// KPOL has no "&": the reference lowers a bitmask to "x != 0" (D-E7).
		return wrap(p.Var + " != 0")
	}
	return p.RawText
}

func actionToKPOLSet(a *Action) string {
	t := a.Target
	switch a.Kind {
	case ActInc:
		return "set " + t + " := " + t + " + 1;"
	case ActDec:
		return "set " + t + " := " + t + " - 1;"
	case ActAdd:
		return "set " + t + " := " + t + " + " + a.Operand.String() + ";"
	case ActSub:
		return "set " + t + " := " + t + " - " + a.Operand.String() + ";"
	}
	return "set " + t + " := " + a.Operand.String() + ";"
}

type eventBinding struct{ event, param string }

// synthesizeDefaultTest builds the AutoGeneratedSanityCheck Proof for multi-concept programs without tests.
func synthesizeDefaultTest(p *Program, byConcept map[string]eventBinding) ([]string, error) {
	entry := &p.Concepts[0]
	for i := range p.Concepts {
		c := &p.Concepts[i]
		if len(c.Rules) > 0 && c.Rules[0].TriggerKind == TriggerWrite {
			entry = c
			break
		}
	}
	b, ok := byConcept[entry.Name]
	if !ok {
		return nil, internalErr("unhandled reference exception KeyError: %s", pyRepr(entry.Name))
	}
	pred := &entry.Rules[0].Predicate
	sample := big.NewInt(10)
	add := func(a *big.Int, d int64) *big.Int { return new(big.Int).Add(a, big.NewInt(d)) }
	switch {
	case pred.Kind == PredRange && pred.Lo != nil && pred.Hi != nil:
		if !pred.Inverted {
			sample = pred.Lo
		} else {
			sample = add(pred.Hi, 10)
		}
	case pred.Kind == PredCmp && pred.Value.Kind == ValueInt:
		v := pred.Value.Int
		inv := pred.Inverted
		pick := func(plain, inverted *big.Int) *big.Int {
			if inv {
				return inverted
			}
			return plain
		}
		switch pred.Op {
		case "<":
			sample = pick(add(v, -1), add(v, 1))
		case "<=":
			sample = pick(v, add(v, 1))
		case ">":
			sample = pick(add(v, 1), add(v, -1))
		case ">=":
			sample = pick(v, add(v, -1))
		case "==":
			sample = pick(v, add(v, 1))
		case "!=":
			sample = pick(add(v, 1), v)
		}
	}
	return []string{
		"Proof " + p.ModuleName + " {",
		"    scenario AutoGeneratedSanityCheck {",
		"        step " + b.event + "(" + b.param + " = " + sample.String() + ");",
		"        expect " + entry.Name + " >= 0;",
		"    }",
		"}",
	}, nil
}

// ProgramToKPOL translates a parsed EKPOL-B64 program to classic KPOL (T_EK, section 10.1).
// When synthesizeProof is set and the program has several concepts but no test, a sanity
// Proof is appended. Embedded tests are executed against the KPOL reference semantics.
func ProgramToKPOL(p *Program, synthesizeProof bool) (string, error) {
	if _, err := ValidateB64(p); err != nil {
		return "", err
	}
	var lines []string
	if len(p.StdinConcepts) > 0 {
		lines = append(lines, "# @stdin "+strings.Join(p.StdinConcepts, ", "))
	}
	if len(p.StdoutConcepts) > 0 {
		lines = append(lines, "# @stdout "+strings.Join(p.StdoutConcepts, ", "))
	}

	lines = append(lines, "Problem "+p.ModuleName+" {", "    Invariants {")
	for i := range p.Concepts {
		c := &p.Concepts[i]
		invName := "I_" + c.Name
		if len(p.Concepts) == 1 {
			invName = "NonNeg"
		}
		lines = append(lines, "        "+invName+": "+c.Name+" >= 0;")
	}
	lines = append(lines, "    }", "}", "")

	lines = append(lines, "Solution "+p.ModuleName+" {")
	for i := range p.Concepts {
		c := &p.Concepts[i]
		lines = append(lines, "    state "+c.Name+": Int32 = "+c.Initial.String()+";")
	}
	lines = append(lines, "")

	byConcept := map[string]eventBinding{}
	eventToParam := map[string]string{}
	for i := range p.Concepts {
		c := &p.Concepts[i]
		r := &c.Rules[0]
		if r.TriggerKind == TriggerWrite {
			ev := canonicalEventName(c, r, len(p.Concepts))
			byConcept[c.Name] = eventBinding{ev, r.ParamName}
			eventToParam[ev] = r.ParamName
			lines = append(lines, "    event "+ev+"("+r.ParamName+": Int32);")
		}
	}
	lines = append(lines, "")

	for i := range p.Concepts {
		c := &p.Concepts[i]
		r := &c.Rules[0]
		onClause := byConcept[c.Name].event
		if r.TriggerKind == TriggerChange {
			onClause = "change(" + r.WatchConcept + ")"
		}
		lines = append(lines,
			"    rule "+canonicalRuleName(c, len(p.Concepts))+" on "+onClause+" when "+predicateToKPOLGuard(&r.Predicate)+" {",
			"        "+actionToKPOLSet(&r.Actions[0]),
			"    }")
	}
	lines = append(lines, "}")

	switch {
	case len(p.Tests) > 0:
		lines = append(lines, "", "Proof "+p.ModuleName+" {")
		for ti := range p.Tests {
			t := &p.Tests[ti]
			lines = append(lines, "    scenario "+t.Name+" {")
			for si := range t.Steps {
				st := &t.Steps[si]
				if st.Kind == StepSend {
					var ev, param string
					if b, ok := byConcept[st.Target]; ok {
						ev, param = b.event, b.param
					} else if dp, ok := eventToParam[st.Target]; ok {
						ev = st.Target
						param = st.ParamName
						if param == "" {
							param = dp
						}
					} else {
						return "", newErr(CodeProof, "test %s: unknown target concept or event %s", pyRepr(t.Name), pyRepr(st.Target))
					}
					lines = append(lines, "        step "+ev+"("+param+" = "+st.Value.String()+");")
				} else {
					lines = append(lines, "        expect "+st.Target+" "+st.Op+" "+st.Value.String()+";")
				}
			}
			lines = append(lines, "    }")
		}
		lines = append(lines, "}")
	case synthesizeProof && len(p.Concepts) > 1:
		extra, err := synthesizeDefaultTest(p, byConcept)
		if err != nil {
			return "", err
		}
		lines = append(lines, "")
		lines = append(lines, extra...)
	}

	text := strings.Join(lines, "\n") + "\n"
	if len(p.Tests) > 0 {
		if err := verifyEmbeddedTests(text); err != nil {
			return "", err
		}
	}
	return text, nil
}

// ToKPOL translates EKPOL source to classic KPOL (reference: transpile_ekpol_to_kpol).
func ToKPOL(src, defaultModuleName string) (string, error) {
	p, err := Parse(src, defaultModuleName)
	if err != nil {
		return "", err
	}
	return ProgramToKPOL(p, false)
}
